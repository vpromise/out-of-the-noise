"""Episode 22 toy: frame-to-frame consistency from correlated starting noise (uses the trained digit model).

A "clip" = 8 frames. Every frame is a digit generated by the DDPM-trained U-Net (DDIM 50 steps, w = 1, label fixed per
clip). Frame k starts from  eps_k = sqrt(rho) * eps_shared + sqrt(1 - rho) * eps_k_own   (unit variance for any rho;
the "mixed noise" idea of PYoCo, Ge et al. 2023).  rho = 0: frames drawn independently; rho = 1: one shared noise.
Motion is IMPOSED by pasting frame k 3 px further right on a 28x52 canvas; the model is not asked to make motion.
What we measure is whether the digit stays the same digit from frame to frame (identity/style flicker):
  flicker   = mean |frame_{k+1} - shift(frame_k, 3 px)| on the canvas, pixels in [0, 1] (0 = perfectly consistent)
  change_px = mean L2 distance between consecutive 28x28 digits, pixels in [0, 1] (784 dims)

  python gpu/video_toy_noise.py  -> arrays/digit_video_noise_correlation.npz, images/digit_video_rho*.png,
                                    results/video_toy_noise.json
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mlx.core as mx  # noqa: E402

from common import ARRAYS, IMAGES, save_grid, to_uint8, write_result  # noqa: E402
from sampling import Denoiser, load_model, sample  # noqa: E402

F, H, W, DX = 8, 28, 52, 3
RHOS = [0.0, 0.5, 0.9, 0.99, 1.0]
N_CLIPS = 20


def paste(frames01):
    """frames01 [F,28,28] in [0,1] -> canvas [F,28,52] with frame k at x = 3k."""
    c = np.zeros((F, H, W), dtype=np.float32)
    for k in range(F):
        c[k, :, DX * k:DX * k + 28] = frames01[k]
    return c


def flicker(canvas):
    out = []
    for k in range(F - 1):
        s = np.zeros_like(canvas[k]); s[:, DX:] = canvas[k][:, :-DX]
        out.append(np.abs(canvas[k + 1] - s).mean())
    return float(np.mean(out))


if __name__ == "__main__":
    m, _ = load_model("ddpm")
    den = Denoiser(m)
    rng = np.random.default_rng(2222)
    shared = rng.standard_normal((N_CLIPS, 1, 28, 28, 1), dtype=np.float32)
    own = rng.standard_normal((N_CLIPS, F, 28, 28, 1), dtype=np.float32)
    labels = np.repeat((np.arange(N_CLIPS) % 10).astype(np.int32)[:, None], F, axis=1)
    res, arr = dict(rows=[]), {}
    for rho in RHOS:
        eps = np.sqrt(rho) * shared + np.sqrt(1 - rho) * own
        x0, _ = sample(den, "ddim", 50, mx.array(eps.reshape(-1, 28, 28, 1)), mx.array(labels.reshape(-1)), 1.0)
        fr = ((np.array(x0)[..., 0] + 1) / 2).reshape(N_CLIPS, F, 28, 28)
        canv = np.stack([paste(f) for f in fr])
        fl = [flicker(c) for c in canv]
        ch = [np.mean([np.sqrt(((f[k + 1] - f[k]) ** 2).sum()) for k in range(F - 1)]) for f in fr]
        res["rows"].append(dict(rho=rho, flicker=float(np.mean(fl)), flicker_std=float(np.std(fl)),
                                change_px=float(np.mean(ch))))
        arr[f"rho{rho:g}_frames"] = to_uint8(fr * 2 - 1)
        arr[f"rho{rho:g}_canvas"] = to_uint8(canv * 2 - 1)
        save_grid(os.path.join(IMAGES, f"digit_video_rho{rho:g}_clips0-3.png"),
                  to_uint8(canv[:4] * 2 - 1).reshape(-1, H, W), nrow=F, scale=2)
        print(res["rows"][-1], flush=True)
    res.update(frames=F, canvas=[H, W], px_per_frame=DX, n_clips=N_CLIPS, model="digit DDPM U-Net (EMA)",
               sampler="DDIM 50, w=1", note=__doc__.split("\n\n")[0] + " " + __doc__.split("\n\n")[1].replace("\n", " "))
    write_result("video_toy_noise", res)
    np.savez_compressed(os.path.join(ARRAYS, "digit_video_noise_correlation.npz"), labels=labels[:, 0], rhos=np.array(RHOS),
                        note="[clip, frame, 28, 28] digits and [clip, frame, 28, 52] canvases (uint8) per rho; "
                             "label = clip % 10; frame k pasted at x = 3k", **arr)
